"""Writes crates/station-backend/src/fake_opus.rs: the Opus packets of the fake
backend's `payload = "real"` mode.

The fake backend has no encoder, so this runs once, by hand, and the output is
committed. It is not part of any build or test. It needs ffmpeg (for the noise)
and opusenc (opus-tools); the output depends on their versions, which are
recorded in the file's header.

    scripts/make-fake-opus-fixture.py > crates/station-backend/src/fake_opus.rs

For each frame duration the protocol allows (10, 20, 40 and 60 ms) it encodes
about a second of band-limited pink noise (300 to 3000 Hz, a fixed seed) at
24 kbit/s with a hard constant bitrate, mono, then takes the packets out of
the Ogg stream. With a hard constant bitrate every packet is
`24000 * frame_ms / 8000` bytes (60 bytes for 20 ms), which is the size of a
real channel's packets. The packets of one duration are written back to back.
"""

import subprocess
import sys
import tempfile
from pathlib import Path

SEED = 20261115
BITRATE_KBIT = 24
# (frame duration in ms, packets to keep, so that each set is about one second)
SETS = [(10, 100), (20, 50), (40, 25), (60, 17)]
SKIP = 2  # the first packets carry the encoder's start-up


def run(args):
    return subprocess.run(args, check=True, capture_output=True)


def version(cmd, flag="--version"):
    out = subprocess.run([cmd, flag], capture_output=True, text=True)
    return (out.stdout or out.stderr).splitlines()[0].strip()


def ogg_packets(data):
    """The packets of an Ogg stream (RFC 3533): pages, lacing values."""
    packets, current, pos = [], b"", 0
    while pos < len(data):
        assert data[pos : pos + 4] == b"OggS", "not an Ogg page"
        nsegs = data[pos + 26]
        lacing = data[pos + 27 : pos + 27 + nsegs]
        pos += 27 + nsegs
        for lace in lacing:
            current += data[pos : pos + lace]
            pos += lace
            if lace < 255:
                packets.append(current)
                current = b""
    return packets


def encode(wav, frame_ms, out):
    run(
        [
            "opusenc",
            "--quiet",
            "--hard-cbr",
            "--bitrate",
            str(BITRATE_KBIT),
            "--framesize",
            str(frame_ms),
            "--downmix-mono",
            str(wav),
            str(out),
        ]
    )
    # Skip OpusHead and OpusTags, then the start-up.
    return ogg_packets(out.read_bytes())[2 + SKIP :]


def rust_bytes(data):
    lines = []
    for i in range(0, len(data), 24):
        chunk = data[i : i + 24]
        lines.append("    " + " ".join(f"0x{b:02x}," for b in chunk))
    return "\n".join(lines)


def main():
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "noise.wav"
        run(
            [
                "ffmpeg",
                "-v",
                "error",
                "-f",
                "lavfi",
                "-i",
                f"anoisesrc=color=pink:seed={SEED}:sample_rate=12000:duration=2:amplitude=0.25",
                "-af",
                "highpass=f=300,lowpass=f=3000",
                "-ac",
                "1",
                str(wav),
            ]
        )
        sets = []
        for frame_ms, count in SETS:
            packets = encode(wav, frame_ms, Path(tmp) / f"{frame_ms}.opus")[:count]
            size = BITRATE_KBIT * frame_ms // 8
            assert len(packets) == count, (frame_ms, len(packets))
            assert all(len(p) == size for p in packets), (frame_ms, {len(p) for p in packets})
            sets.append((frame_ms, size, b"".join(packets)))
    print("// SPDX-License-Identifier: GPL-3.0-only")
    print("//! Opus packets for the fake backend's `payload = \"real\"` mode.")
    print("//!")
    print("//! Generated by `scripts/make-fake-opus-fixture.py`; do not edit. About a")
    print(f"//! second of band-limited pink noise (seed {SEED}), mono, hard constant")
    print(f"//! bitrate {BITRATE_KBIT} kbit/s, for each frame duration, so every packet of a set")
    print("//! has the same size: a real channel's. Made with")
    print(f"//! `{version('opusenc')}` and `{version('ffmpeg', '-version').split(' Copyright')[0]}`.")
    print()
    for frame_ms, size, data in sets:
        print(f"/// {len(data) // size} packets of {frame_ms} ms, {size} bytes each, back to back.")
        print(f"pub(crate) const PACKETS_{frame_ms}_MS: &[u8] = &[")
        print(rust_bytes(data))
        print("];")
        print()


main()
