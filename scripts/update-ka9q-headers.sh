#!/bin/sh
# SPDX-License-Identifier: GPL-3.0-only
#
# Re-vendor the pinned ka9q-radio headers used by the backend-ka9q TLV codegen.
#
# Usage:
#   scripts/update-ka9q-headers.sh <commit> [<local ka9q-radio clone>]
#
# Copies src/status.h and src/rtp.h at <commit> into
# crates/backend-ka9q/vendor/ka9q-radio/ and rewrites VERSION with the
# upstream URL, the commit and the SHA-256 of each file. Without a local clone
# the script fetches the commit from the upstream repository into a temporary
# directory. Changing the pinned headers is deliberate: review the diff of the
# generated tag enums (cargo test -p backend-ka9q) before committing.
set -eu

UPSTREAM_URL="https://github.com/ka9q/ka9q-radio"
FILES="status.h rtp.h"

usage() {
    echo "usage: $0 <commit> [<local ka9q-radio clone>]" >&2
    exit 2
}

if [ "$#" -lt 1 ] || [ "$#" -gt 2 ]; then
    usage
fi
COMMIT="$1"
case "$COMMIT" in
    *[!0-9a-f]* | "") echo "error: commit must be a full lowercase hex SHA-1" >&2; exit 2 ;;
esac
[ "${#COMMIT}" -eq 40 ] || { echo "error: commit must be a full 40-character SHA-1" >&2; exit 2; }

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
DEST="$SCRIPT_DIR/../crates/backend-ka9q/vendor/ka9q-radio"
mkdir -p "$DEST"

sha256() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1
    fi
}

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT INT TERM

if [ "$#" -eq 2 ]; then
    SRC="$2"
else
    SRC="$TMP/ka9q-radio"
    git init -q "$SRC"
    git -C "$SRC" remote add origin "$UPSTREAM_URL"
    git -C "$SRC" fetch -q --depth 1 origin "$COMMIT"
fi

for f in $FILES; do
    git -C "$SRC" show "$COMMIT:src/$f" >"$TMP/$f"
done

for f in $FILES; do
    cp "$TMP/$f" "$DEST/$f"
done

{
    echo "# Pinned ka9q-radio headers. Generated by scripts/update-ka9q-headers.sh; do not edit."
    echo "upstream $UPSTREAM_URL"
    echo "commit $COMMIT"
    for f in $FILES; do
        echo "sha256 $(sha256 "$DEST/$f") $f"
    done
} >"$DEST/VERSION"

echo "Vendored ka9q-radio $COMMIT into $DEST"
